// routes/tracking-page.js — GET /track/:code
// Public shipment-status page opened by scanning a label QR code. No
// sign-in: anyone holding the PRO (printed on the box) can see it, so the
// page shows ONLY what a carrier tracking page shows — PRO, carrier +
// service, status, origin/destination CITIES, pieces, weight, date, and a
// TEST badge for sandbox shipments. It NEVER shows addresses, contact
// details, order numbers, or charges. Tracking
// pages are not indexed (noindex). Mounted at /track in server.js,
// before the SPA fallback, with no auth or approval gate.
'use strict';

const express = require('express');
const db = require('../db');
const { store } = require('../lib/store');

const router = express.Router();

const escHtml = (s) =>
  String(s == null ? '' : s)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

const STATUS_LABELS = {
  awaiting_payment: 'Awaiting payment',
  dg_review: 'Under review',
  scheduled: 'Scheduled',
  purchased: 'Purchased',
  cancelled: 'Cancelled',
};

function mapRow(row) {
  let bol = {};
  try {
    bol = typeof row.bol_json === 'object' ? row.bol_json || {} : JSON.parse(row.bol_json || '{}');
  } catch {
    /* ignore */
  }
  return {
    id: row.id,
    status: row.status,
    carrier: row.carrier,
    service: row.service_level,
    tracking_code: row.tracking_code,
    created_at: row.created_at,
    test_mode: !!row.test_mode,
    bol,
  };
}

async function findByTrackingCode(code) {
  const clean = String(code || '').trim();
  if (!clean) return null;
  const mem = store.orders.find((o) => o.tracking_code === clean);
  if (mem) {
    return {
      id: mem.id,
      status: mem.status,
      carrier: mem.carrier,
      service: mem.service_level || mem.service,
      tracking_code: mem.tracking_code,
      created_at: mem.created_at,
      test_mode: !!mem.test_mode,
      bol: mem.bol || {},
    };
  }
  if (db.isEnabled()) {
    try {
      for (const candidate of [clean, clean.toUpperCase()]) {
        const r = await db.query('SELECT * FROM orders WHERE tracking_code = $1', [candidate]);
        if (r.rows.length) return mapRow(r.rows[0]);
      }
    } catch {
      /* fall through to not found */
    }
  }
  return null;
}

function cityLine(p) {
  return [p.city, p.state || p.province].filter(Boolean).join(', ') || '—';
}

function pageHtml({ title, body }) {
  return `<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${escHtml(title)}</title>
<style>
body{font-family:Arial,Helvetica,sans-serif;margin:0;color:#111;background:#f4f6f8}
.card{max-width:520px;margin:24px auto;background:#fff;border:1px solid #ddd;border-radius:12px;padding:24px}
h1{font-size:22px;margin:0 0 4px}.pro-label{font-size:13px;font-weight:700;letter-spacing:2px;color:#555;margin:12px 0 0}.pro{font-size:26px;font-weight:bold;letter-spacing:1px;margin:2px 0 8px}
.badge{display:inline-block;background:#e6f0e6;border:1px solid #9cc49c;color:#1e5c1e;border-radius:999px;padding:4px 12px;font-weight:700;font-size:14px}
.badge.test{background:#fff3cd;border-color:#d9a400;color:#5c4300}
table{width:100%;border-collapse:collapse;font-size:15px;margin-top:16px}
td{padding:8px 4px;border-bottom:1px solid #eee;vertical-align:top}
td:first-child{color:#555;width:40%}
.note{font-size:13px;color:#555;margin-top:20px}
a{color:#1e3a5f}
</style></head><body><div class="card">${body}</div></body></html>`;
}

router.get('/:code', async (req, res) => {
  const order = await findByTrackingCode(req.params.code);
  if (!order) {
    return res.status(404).send(pageHtml({
      title: 'Tracking code not found',
      body: `<h1>Tracking code not found</h1>
<p>No shipment matches <strong>${escHtml(req.params.code)}</strong>. Check the code on the label and try again.</p>
<p class="note">Generated by ShipRate. <a href="/">Back to ShipRate</a></p>`,
    }));
  }
  const b = order.bol || {};
  const shipper = b.shipper || {};
  const consignee = b.consignee || {};
  const pkgCount = (b.packages || []).reduce((n, p) => n + (Number(p.qty) || 0), 0);
  const status = STATUS_LABELS[order.status] || order.status || '—';
  const date = order.created_at ? new Date(order.created_at).toLocaleDateString('en-CA') : '—';
  res.send(pageHtml({
    title: `Shipment ${order.tracking_code}`,
    body: `<h1>Shipment tracking</h1>
<div class="pro-label">PRO Number</div>
<div class="pro">${escHtml(order.tracking_code)}</div>
<p><span class="badge">${escHtml(status)}</span>${order.test_mode ? ' <span class="badge test">TEST shipment</span>' : ''}</p>
<table><tbody>
<tr><td>Carrier</td><td><strong>${escHtml(order.carrier || '—')}${order.service ? ' — ' + escHtml(order.service) : ''}</strong></td></tr>
<tr><td>From</td><td><strong>${escHtml(cityLine(shipper))}</strong></td></tr>
<tr><td>To</td><td><strong>${escHtml(cityLine(consignee))}</strong></td></tr>
<tr><td>Pieces</td><td><strong>${pkgCount || '—'}</strong></td></tr>
<tr><td>Weight</td><td><strong>${b.total_weight_lbs ?? '—'} lb</strong></td></tr>
<tr><td>Booked</td><td>${escHtml(date)}</td></tr>
</tbody></table>
<p class="note">Full details are on the bill of lading that came with this shipment. Generated by ShipRate. <a href="/">Back to ShipRate</a></p>`,
  }));
});

module.exports = router;
